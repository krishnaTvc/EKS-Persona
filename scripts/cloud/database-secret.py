#!/usr/bin/env python3
"""Create the Kubernetes Secret without placing passwords in Helm values/state/logs."""
import base64
import json
import os
import re
import subprocess

mapping={
    'mysql_root_password':'MYSQL_ROOT_PASSWORD',
    'registration_password':'REGISTRATION_PASSWORD',
    'persona_password':'PERSONA_PASSWORD',
}
data={}
for key,env in mapping.items():
    value=os.environ.get(env,'').strip()
    if not re.fullmatch('[a-f0-9]{48}',value):
        raise SystemExit(f'{env} must be the 48-character hexadecimal password generated by generate-passwords.py')
    data[key]=base64.b64encode((value+'\n').encode()).decode()
existing=subprocess.run(['kubectl','-n','persona','get','secret','persona-db','--ignore-not-found','-o','json'],capture_output=True,text=True)
if existing.returncode:
    raise SystemExit('Could not inspect persona-db; check EKS access and namespace permissions')
if existing.stdout.strip():
    if json.loads(existing.stdout).get('data')!=data:
        raise SystemExit('Configured passwords differ from the existing Secret. Retained MySQL users are not automatically rotated. Restore the original inputs or perform an explicit coordinated rotation.')
    print('Existing database Secret matches; preserving it.')
else:
    document={'apiVersion':'v1','kind':'Secret','metadata':{'name':'persona-db','namespace':'persona'},'type':'Opaque','data':data}
    subprocess.run(['kubectl','create','-f','-'],input=json.dumps(document),text=True,check=True)
